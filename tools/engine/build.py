#!/usr/bin/env python3
"""Turn Bend's ES module output into qml/Hueometry/js/engine.mjs.

Two changes, both checked so a Bend upgrade that moves them fails loudly:

1. Qt's JavaScript engine cannot parse BigInt literals. They appear only in
   Bend's F32 text rounding helper, which the engine never calls (it has no
   F32). That helper is replaced with one that throws.
2. The default export becomes a constant, and each def of engine/api.bend is
   also exported by name, so QML can import the module directly.
"""
import re
import sys

src, out, version = sys.argv[1], sys.argv[2], sys.argv[3]
js = open(src, encoding="utf-8").read()

start = js.find("const f32_round = function f32_round(s) {")
end = js.find("\n};\n", start)
if start < 0 or end < 0:
    sys.exit("build.py: f32_round not found; check the Bend upgrade")
js = js[:start] + (
    "const f32_round = function f32_round(s) {\n"
    '  throw "hueometry: F32 text is not supported in this build";\n'
    "};\n"
) + js[end + 4:]
if re.search(r"\bBigInt\b|\b\d+n\b(?![\"'])", js.split("// Program", 1)[0]):
    sys.exit("build.py: the runtime still uses BigInt; Qt cannot load it")

marker = "export default {\n"
at = js.rfind(marker)
if at < 0:
    sys.exit("build.py: no default export found")
body = js[at + len(marker):]
names = re.findall(r'^  "([A-Za-z_][A-Za-z0-9_]*)": ', body, re.M)
if not names:
    sys.exit("build.py: no API defs found")
js = js[:at] + "const BEND = {\n" + body
js += "\nexport default BEND;\n" + "".join(
    f'export const {n} = BEND["{n}"];\n' for n in names)

header = (
    f"// Generated by bin/engine from engine/api.bend with Bend {version}.\n"
    "// Do not edit: change the .bend sources and run bin/engine.\n"
)
open(out, "w", encoding="utf-8").write(header + js)
print(f"{out}: {len(js.encode())} bytes, exports {', '.join(names)}")
