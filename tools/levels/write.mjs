// Writes a level module: one JSON value as an ES module's default export.
import { writeFileSync } from "node:fs";

export function writeModule(name, value) {
  const out = new URL(`../../qml/Hueometry/js/${name}`, import.meta.url);
  // one level per line: compact, and still diffs well
  const json = JSON.stringify(value).replace(/\},\{"seed"/g, '},\n{"seed"');
  writeFileSync(out, "// Generated by bin/levels. Do not edit.\nexport default " + json + ";\n");
  console.log(`wrote ${out.pathname}`);
}
